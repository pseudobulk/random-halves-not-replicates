"""Model evaluation step 1 and negative controls: tables and the clone-gain figure.
Inputs (in <results_dir>): detail_D1..D4.json and detail_K562_RPE1.json (me_score_detail.py), clonality.json
(me_clonality.py), clone_tests_D1..D4.json (clone_tests_cd4.py; expression cross energy, table only),
cross_donor.json (me_cross_donor.py), fitcheck_<run>.json (me_fitcheck.py).
Clone gain = A - B over all test targets (inert and strong together; for K562 -> RPE1 the clean groups inert + strong,
the mismatched group separately); SEs clustered by target.
Figure: (a) within-donor clone gain against donor clonality, vc = TRBC clone variance of a guide mean (mean of the
resting and stimulated values; size-free, unlike var_z, which ties D2 and D3); (b) the same models when truth comes from
a separate transduction: other donor (mean over the 12 donor pairs, whisker = range) and K562 -> RPE1 (clean groups,
+- SE). The additive baseline is left out of the figure (within 0.002 of copy; in the table).
Outputs: <results_dir>/summary_table.md, <fig_dir>/clone_gain_vs_clonality.{png,pdf}.
Usage: me_summary.py <results_dir> <fig_dir>"""
import os, sys, json
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

DONORS = ("D1", "D2", "D3", "D4")
MODELS = (("mean", "context mean"), ("copy", "copy"), ("additive", "additive"), ("linear", "linear (ridge)"),
          ("state_transition", "STATE Transition"))
COL = {"copy": "#2a78d6", "additive": "#eb6834", "linear": "#1baf7a", "state_transition": "#eda100"}   # validated (dataviz)
MK = {"copy": "o", "additive": "s", "linear": "^", "state_transition": "D"}
INK, MUTED, GRID = "#2b2b2b", "#6b6b6b", "#e4e4e0"


def J(d, f):
    p = os.path.join(d, f)
    return json.load(open(p)) if os.path.exists(p) else None


def regroup(per_guide, groups):
    """A, B, A - B over the guides of the given groups; SE over target means"""
    rr = [r for r in per_guide if r[1] in groups]
    tg = sorted({r[0] for r in rr}); o = dict(n_guides=len(rr), n_targets=len(tg))
    for k, f in (("A", lambda r: r[2]), ("B", lambda r: r[3]), ("AB", lambda r: r[2] - r[3])):
        per_t = np.array([np.mean([f(r) for r in rr if r[0] == t]) for t in tg])
        o[k] = float(np.mean([f(r) for r in rr])); o[k + "_se"] = float(per_t.std(ddof=1) / np.sqrt(len(tg)))
    return o


def cells(v):
    return ["%.3f (%.3f)" % (v["A"], v["A_se"]), "%.3f (%.3f)" % (v["B"], v["B_se"]), "%.3f (%.3f)" % (v["AB"], v["AB_se"])]


def main():
    rd, fd = sys.argv[1:3]; os.makedirs(fd, exist_ok=True)
    det = {d: J(rd, "detail_%s.json" % d) for d in DONORS}; det = {d: v for d, v in det.items() if v}
    rep = J(rd, "detail_K562_RPE1.json"); xd = J(rd, "cross_donor.json"); cl = J(rd, "clonality.json")
    ct = {d: J(rd, "clone_tests_%s.json" % d) for d in DONORS}
    fit = {r: J(rd, "fitcheck_%s.json" % r) for r in DONORS + ("K562_RPE1", "fr_IFNg_f0", "fr_IFNg_f1")}
    ds = list(det)
    vc = {d: (cl[d]["rest"]["vc"] + cl[d]["stim48"]["vc"]) / 2 for d in ds}
    L = ["# Model evaluation: per-donor scores and no-shared-clone controls", "",
         "Generated by `code/model_eval/me_summary.py`. A: truth = the guide's own target-context cells (within a CD4 donor "
         "these share the input's clones). B: truth = the other guide of the same target (independent replicate). Pearson "
         "over genes of predicted vs observed effect, target gene excluded; mean over test guides; SE (in brackets) over "
         "target means.", "", "## 1. Clonality and test sets (CD4, resting → stimulated 48 h)", "",
         "| Donor | TRBC var_z rest / stim | TRBC vc rest / stim (SE) | inert cross energy, random halves, rest | test targets inert / strong (dropped) | genes |",
         "|---|---|---|---|---|---|"]
    for d in ds:
        c = cl[d]; x = det[d]
        ce = ct[d]["rest"]["depth"]["random_half"]["inert"]["cross_per_target"] if ct.get(d) else float("nan")
        L.append("| %s | %.0f / %.0f | %.3f / %.3f (%.3f) | %.1f | %d / %d (%d) | %d |" % (
            d, c["rest"]["var_z"], c["stim48"]["var_z"], c["rest"]["vc"], c["stim48"]["vc"], c["rest"]["vc_se"], ce,
            x["n_test_targets"]["inert"], x["n_test_targets"]["strong"], x["n_dropped_test"], x["n_genes"]))
    for grp, title in (("all", "All test targets"), ("inert", "Unexpressed targets (no true effect)"), ("strong", "Knocked-down targets (strength-matched)")):
        L += ["", "## 2%s. Within donor: %s" % ({"all": "a", "inert": "b", "strong": "c"}[grp], title), "",
              "| Model | " + " | ".join("%s A | %s B | %s A − B" % (d, d, d) for d in ds) + " |", "|---" * (1 + 3 * len(ds)) + "|"]
        for m, name in MODELS + (("truth_A_vs_B", "reference: truth A as prediction"),):
            L.append("| %s | %s |" % (name, " | ".join(sum((cells(det[d]["models"][m][grp]) for d in ds), []))))
    if xd:
        L += ["", "## 3. No shared clone, same guides: predictions of donor d scored against donor e", "",
              "A′ = the same guide in donor e (separate transduction), B′ = the other guide in donor e. Truth from all of the "
              "guide's 48 h cells (uncapped), so less noisy than the within-donor truth.", "",
              "| Source → truth donor | guides | " + " | ".join("%s A′ − B′" % n for m, n in MODELS[1:]) + " | STATE A′ | STATE B′ |",
              "|---" * (3 + len(MODELS)) + "|"]
        for pair, r in xd["pairs"].items():
            a = r["state_transition"]["all"]
            L.append("| %s | %d | %s | %.3f | %.3f |" % (pair, a["n_guides"], " | ".join("%.3f (%.3f)" % (r[m]["all"]["AB"], r[m]["all"]["AB_se"]) for m, _ in MODELS[1:]), a["A"], a["B"]))
    if rep:
        L += ["", "## 4. Separate screens: K562 essential → RPE1 essential (Replogle 2022), element level", "",
              "A = the same dual-sgRNA element in RPE1, B = the target's other element in RPE1. Clean groups: 'inert' (target "
              "not in either file's gene list or control < 0.01) and 'strong' (both elements knock the target down in both "
              "screens). 'Mismatched': one element knocks down and the other does not, consistently in both screens, so "
              "A − B > 0 is expected from the elements themselves.", "",
              "| Model | clean (inert + strong) A | B | A − B | mismatched A | B | A − B |", "|---|---|---|---|---|---|---|"]
        for m, name in MODELS + (("truth_A_vs_B", "reference: truth A as prediction"),):
            pg = rep["models"][m]["per_guide"]
            L.append("| %s | %s | %s |" % (name, " | ".join(cells(regroup(pg, ("inert", "strong")))), " | ".join(cells(regroup(pg, ("mismatched",))))))
        L.append("")
        L.append("Guides / targets: clean %d / %d, mismatched %d / %d." % tuple(
            x for g in (("inert", "strong"), ("mismatched",)) for x in (regroup(rep["models"]["copy"]["per_guide"], g)["n_guides"], regroup(rep["models"]["copy"]["per_guide"], g)["n_targets"])))
    fl = [(r, f) for r, f in fit.items() if f]
    if fl:
        L += ["", "## 5. Fit check: STATE Transition reproduces the stimulated effects of training guides", "",
              "Fit: Pearson between a training guide's predicted and observed stimulated effect; 'other guides' = the same "
              "prediction against other training guides' observed effects (what a shared response alone gives). "
              "Re-prediction: %d saved test guides predicted again through the TOML override; agreement with the saved "
              "prediction vs with other guides' saved predictions. It is not exact because STATE conditions on sampled "
              "control cells." % (fl[0][1]["n_check"]), "",
              "| Run | training guides | fit r (SE) | fit r, other guides | re-prediction r, mean (range) | re-prediction r, other guides |",
              "|---|---|---|---|---|---|"]
        for r, f in fl:
            L.append("| %s | %d | %.3f (%.3f) | %.3f | %.2f (%.2f–%.2f) | %.2f |" % (r, f["n_fit_guides"], f["fit_pearson"], f["fit_se"],
                     f["fit_offdiag_pearson"], f["check_mean_r"], f["check_min_r"], max(f["check_r"]), f["check_offdiag_mean_r"]))
    # step 3: Frangieh (low clonality) and clonality in expression on one scale
    def two(j):
        return [v for k, v in j.items() if isinstance(v, dict)]
    vcx = {d: J(rd, "vc_expr_%s.json" % d) for d in DONORS + ("fr_IFNg", "fr_Coculture")}
    vcx = {d: v for d, v in vcx.items() if v}
    xe = {d: np.mean([s["vc_expr"] for s in two(v)]) for d, v in vcx.items()}
    fr = {p: [J(rd, "detail_fr_%s_f%d.json" % (p, k)) for k in (0, 1)] for p in ("IFNg", "Cocu")}
    fr = {p: v for p, v in fr.items() if all(v)}
    bds = {d: J(rd, "baselines_ds48_75_%s.json" % d) for d in DONORS}; bds = {d: v for d, v in bds.items() if v}

    def frrows(p, m):
        return sum((f["models"][m]["per_guide"] for f in fr[p] if m in f["models"]), [])

    def pooled(b, m):   # inert + strong of a pilot_baselines.json, guide-weighted; SE over guides
        v = [b["models"][m][k] for k in ("inert", "strong")]; n = sum(x["n"] for x in v)
        return sum(x["n"] * x["leak"] for x in v) / n, np.sqrt(sum((x["n"] * x["leak_se"]) ** 2 for x in v)) / n
    if vcx:
        L += ["", "## 6. Step 3: Frangieh 2021 (melanoma, Control → IFN-γ / co-culture) against CD4 on one clonality scale", "",
              "vc_expr: random-half cross product of a null unit's deviation over the run's evaluation genes, divided by the "
              "summed per-cell variance (me_vc_expr.py; CD4 null units = guides of unexpressed targets, Frangieh = "
              "non-targeting sgRNAs). '40 cells' = the same after subsampling every unit to 40 cells. 'Two guides' = the cross "
              "product between the two guides of a null target (independent transductions).", "",
              "| Data | median cells per unit (source / target) | vc_expr source | vc_expr target | mean | mean, 40 cells | two guides | TRBC vc |",
              "|---|---|---|---|---|---|---|---|"]
        for d, v in vcx.items():
            s = two(v)
            L.append("| %s | %.0f / %.0f | %.4f (%.4f) | %.4f (%.4f) | %.4f | %.4f | %+.4f / %+.4f | %s |" % (
                d, s[0]["median_cells_per_unit"], s[1]["median_cells_per_unit"], s[0]["vc_expr"], s[0]["vc_expr_se"],
                s[1]["vc_expr"], s[1]["vc_expr_se"], xe[d], np.mean([x["vc_expr_ds"] for x in s]),
                s[0]["vc_guide"], s[1]["vc_guide"], "%.3f" % vc[d] if d in vc else "–"))
    for p, title in (("IFNg", "Control → IFN-γ"), ("Cocu", "Control → co-culture (baselines only)")):
        if p not in fr:
            continue
        L += ["", "### Frangieh %s, two cross-fit folds pooled" % title, "",
              "Groups: 'null' = pairs of non-targeting sgRNAs (no true effect), 'gene' = the two best-covered sgRNAs of a "
              "knocked-out gene.", "", "| Model | null A | B | A − B | gene A | B | A − B | all A − B |", "|---|---|---|---|---|---|---|---|"]
        for m, name in MODELS + (("truth_A_vs_B", "reference: truth A as prediction"),):
            rows = frrows(p, m)
            if not rows:
                continue
            L.append("| %s | %s | %s | %s |" % (name, " | ".join(cells(regroup(rows, ("null",)))), " | ".join(cells(regroup(rows, ("gene",)))),
                                               "%.3f (%.3f)" % (lambda g: (g["AB"], g["AB_se"]))(regroup(rows, ("null", "gene")))))
        g = regroup(frrows(p, "copy"), ("null",)); h = regroup(frrows(p, "copy"), ("gene",))
        L += ["", "Guides / targets: null %d / %d, gene %d / %d." % (g["n_guides"], g["n_targets"], h["n_guides"], h["n_targets"])]
    if bds and fr:
        L += ["", "### Clone gain at matched cells per test guide (48 source / 75 target, the Frangieh medians)", "",
              "CD4 test guides subsampled (me_downsample.py), baselines refit; Frangieh at its own cells. CD4: unexpressed + "
              "knocked-down targets, guide-weighted, SE over guides; Frangieh: null + gene, SE over targets.", "",
              "| Data | vc_expr | copy A − B | additive A − B | linear A − B |", "|---|---|---|---|---|"]
        for d in DONORS:
            if d in bds:
                L.append("| %s | %.4f | %s |" % (d, xe[d], " | ".join("%.3f (%.3f)" % pooled(bds[d], m) for m in ("copy", "additive", "linear"))))
        for p, key in (("IFNg", "fr_IFNg"), ("Cocu", "fr_Coculture")):
            if p in fr:
                L.append("| Frangieh %s | %.4f | %s |" % (p, xe.get(key, np.nan), " | ".join(
                    "%.3f (%.3f)" % (lambda g: (g["AB"], g["AB_se"]))(regroup(frrows(p, m), ("null", "gene"))) for m in ("copy", "additive", "linear"))))
    open(os.path.join(rd, "summary_table.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    # figure: (a) within donor against clonality; (b) the same models when input and truth share no clone
    plt.rcParams.update({"font.size": 7, "axes.edgecolor": MUTED, "axes.labelcolor": INK, "xtick.color": MUTED,
                         "ytick.color": MUTED, "font.family": "DejaVu Sans"})
    PM = [(m, n) for m, n in MODELS[1:] if m != "additive"]   # additive is within 0.002 of copy everywhere (table)
    three = bool(bds and fr and vcx)
    fig, axes = plt.subplots(1, 3 if three else 2, figsize=(10.0 if three else 7.0, 3.1), sharey=True,
                             gridspec_kw=dict(width_ratios=[1.6, 1, 1.5] if three else [1.6, 1]))
    ax = axes[0]; order = sorted(ds, key=lambda d: vc[d])
    for m, name in PM:
        x = np.array([vc[d] for d in order])
        y = np.array([det[d]["models"][m]["all"]["AB"] for d in order]); e = np.array([det[d]["models"][m]["all"]["AB_se"] for d in order])
        ax.plot(x, y, color=COL[m], lw=1.2, zorder=2)
        ax.errorbar(x, y, yerr=e, fmt=MK[m], ms=4.5, color=COL[m], mec="white", mew=0.8, elinewidth=0.8, capsize=0, zorder=3, label=name)
    top = max(det[d]["models"]["linear"]["all"]["AB"] for d in ds)
    for d in ds:
        ax.annotate(d, (vc[d], top), xytext=(0, 9), textcoords="offset points", ha="center", color=MUTED, fontsize=6.5)
    ax.set_xlim(0, 0.6)
    ax.set_xlabel("Donor clonality: TRBC clone variance of a guide mean\n(units of per-cell variance)")
    ax.set_title("a  Same donor: input and truth A share clones", loc="left", fontsize=7.5, color=INK)
    ax.set_ylabel("Clone gain, A − B (Pearson)")
    ax.legend(frameon=False, loc="upper left", fontsize=6.5, handletextpad=0.3)
    ax = axes[1]; cats = []
    if xd:
        cats.append(("other donor\n(12 donor pairs;\nwhisker = range)", lambda m: (np.mean([r[m]["all"]["AB"] for r in xd["pairs"].values()]),
                     [[np.mean([r[m]["all"]["AB"] for r in xd["pairs"].values()]) - min(r[m]["all"]["AB"] for r in xd["pairs"].values())],
                      [max(r[m]["all"]["AB"] for r in xd["pairs"].values()) - np.mean([r[m]["all"]["AB"] for r in xd["pairs"].values()])]])))
    if rep:
        cats.append(("K562 → RPE1,\nseparate screens\n(13 targets; ± SE)", lambda m: (regroup(rep["models"][m]["per_guide"], ("inert", "strong"))["AB"],
                     [regroup(rep["models"][m]["per_guide"], ("inert", "strong"))["AB_se"]])))
    for i, (lab, f) in enumerate(cats):
        for j, (m, name) in enumerate(PM):
            y, e = f(m)
            ax.errorbar([i + (j - 1) * 0.16], [y], yerr=e, fmt=MK[m], ms=4.5, color=COL[m], mec="white", mew=0.8, elinewidth=0.8, capsize=0, zorder=3)
    ax.set_xticks(range(len(cats))); ax.set_xticklabels([c[0] for c in cats], fontsize=6.5); ax.set_xlim(-0.6, len(cats) - 0.4)
    ax.tick_params(axis="x", length=0)
    ax.set_title("b  Truth from a separate transduction", loc="left", fontsize=7.5, color=INK)
    if three:   # (c) clone gain at matched cells per guide against clonality in expression, CD4 and Frangieh
        ax = axes[2]; order = sorted(bds, key=lambda d: xe[d])
        for m, name in PM:
            if m != "state_transition":   # CD4 STATE was not retrained at matched cells; Frangieh STATE is at its own cells
                x = [xe[d] for d in order]; y = [pooled(bds[d], m)[0] for d in order]; e = [pooled(bds[d], m)[1] for d in order]
                ax.plot(x, y, color=COL[m], lw=1.2, zorder=2)
                ax.errorbar(x, y, yerr=e, fmt=MK[m], ms=4.5, color=COL[m], mec="white", mew=0.8, elinewidth=0.8, capsize=0, zorder=3)
            for p, key, dx in (("IFNg", "fr_IFNg", 0.0), ("Cocu", "fr_Coculture", 0.0)):
                if p in fr and key in xe and frrows(p, m):
                    g = regroup(frrows(p, m), ("null", "gene"))
                    ax.errorbar([xe[key] + dx], [g["AB"]], yerr=[g["AB_se"]], fmt=MK[m], ms=4.5, mfc="white", color=COL[m], mew=1.0,
                                elinewidth=0.8, capsize=0, zorder=3)
        for d in order:
            ax.annotate(d, (xe[d], top), xytext=(0, 9), textcoords="offset points", ha="center", color=MUTED, fontsize=6.5)
        ax.annotate("Frangieh\n(open)", (xe.get("fr_IFNg", 0), top), xytext=(0, 4), textcoords="offset points", ha="left", color=MUTED, fontsize=6.5)
        ax.set_xlim(-0.001, 0.026)
        ax.set_xlabel("Clonality in expression, vc_expr\n(shared deviation of a null guide / per-cell variance)")
        ax.set_title("c  Matched cells per guide (48 / 75): CD4 vs Frangieh", loc="left", fontsize=7.5, color=INK)
    for ax in axes:
        ax.axhline(0, color=MUTED, lw=0.6, ls=":"); ax.grid(axis="y", color=GRID, lw=0.6); ax.set_axisbelow(True)
        for sp in ("top", "right"):
            ax.spines[sp].set_visible(False)
    axes[0].set_ylim(-0.05, top + 0.06)
    fig.tight_layout()
    for ext in ("png", "pdf"):
        fig.savefig(os.path.join(fd, "clone_gain_vs_clonality.%s" % ext), dpi=200)
    print("wrote", os.path.join(rd, "summary_table.md"))


if __name__ == "__main__":
    main()
